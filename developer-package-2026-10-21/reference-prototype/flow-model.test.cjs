const assert=require('node:assert/strict');
const J=require('./flow-model.js');
const initial={situation:'planned',age:'adult',basis:'study',education:'admitted',visa:'visa',readiness:'none',university:'sutd',housing:'dorm'};
let s={...initial};
const step=(event,data,hero)=>{s=J.apply(s,event,data);if(hero)assert.equal(J.model(s).hero.id,hero);};
step('invite_request',{},'invitation');assert.equal(J.model(s).hero.status,'waiting');
assert.throws(()=>J.apply(s,'visa_received'));
step('invite_received',{},'visa');step('visa_submit',{},'visa');step('visa_received',{},'prepare');step('prepared',{},'entry');
assert.equal(J.model(s).stage,'before');
step('entry',{date:'2026-10-20',purpose:'study'},'visa_date');assert.equal(J.model(s).stage,'arrival');
step('visa_date',{date:'2027-03-01'},'documents');step('documents',{},'office');step('office',{},'registration');
step('registration_submit',{},'registration');assert.equal(J.model(s).hero.status,'waiting');
step('registration_received',{date:'2027-04-19'},'medical');assert.equal(J.model(s).stage,'study');
assert.equal(J.tasks(s).find(t=>t.id==='medical').status,'check');
assert.throws(()=>J.apply(s,'registration_received',{date:'2027-04-19'}));
const undone=J.undo(s);assert.equal(J.tasks(undone).find(t=>t.id==='registration').status,'waiting');assert.equal(J.model(undone).stage,'arrival');
let late={...initial,situation:'arrived',readiness:'',entryDate:'2026-10-20',purpose:'study',office:'yes',registration:'yes',registrationExpiry:'2027-04-19'};
assert.equal(J.model(late).hero.id,'visa_date');assert.equal(J.tasks(late).find(t=>t.id==='prepare').status,'past');
late=J.apply(late,'visa_date',{date:'2027-03-01'});assert.equal(J.model(late).hero.id,'documents');
assert.equal(J.tasks(late).find(t=>t.id==='office').status,'done');
const early=J.apply(initial,'entry',{date:'2026-10-20',purpose:'study'});assert.equal(J.model(early).stage,'arrival');assert.equal(J.tasks(early).find(t=>t.id==='invitation').status,'past');
assert.throws(()=>J.apply(initial,'entry',{date:'2099-01-01',purpose:'study'}));
const other=J.apply(initial,'entry',{date:'2026-10-20',purpose:'other'});assert.equal(J.model(other).hero.id,'purpose');assert.throws(()=>J.apply(other,'office'));
const free={...initial,visa:'visa_free'};assert.equal(J.model(free).hero.id,'prepare');assert.ok(!J.tasks(free).some(t=>t.id==='visa'));
const unsupported={...initial,age:'minor'};assert.equal(J.model(unsupported).hero.id,'support');assert.equal(J.model(J.apply(unsupported,'consult')).hero.status,'waiting');
assert.deepEqual(J.model(JSON.parse(JSON.stringify(s))),J.model(s));
console.log('PASS: full path, late entry, early arrival, dependency guards, no duplicate event, undo, special purpose, visa-free, support, persistence');
